"""Assemble, gate, publish and roll back a static site release (docs/v2/HOSTING.md, "Releases").

  assemble  copy the built web app (web/dist, built in static mode) and the data shards (site/data)
            into one release folder, add the security headers and redirects, and write
            release-manifest.json: the release id, the git commit, the data and model it was built
            from, and the sha256 and size of every file.
  gate      read the release exactly as it will be published and refuse it on any failure:
            the manifest matches the files; the file count and sizes fit Workers static assets;
            every recorded answer was generated by the configured model and prompt and says when;
            every citation resolves to a page in the answer's own evidence, with its text; every
            story carries a comparability block that its caption does not overstate; no retired
            story is on a featured surface; every dated note about a recorded answer is attached
            to it; the data hashes match config/scopes.toml; no curated question is missing a
            recorded answer unless config/release_allow_missing.json lists it with a reason; no
            text that looks like a secret; and the web source renders no raw HTML.
  publish   gate, then upload the release as a new version of the site Worker and deploy it
            (npx wrangler, with the account owner's credentials).
  rollback  deploy an earlier version again: one command.

    python scripts/v2/build_release.py assemble --release-id 2026-10-30.1 --api-origin https://api.archiveargues.org
    python scripts/v2/build_release.py gate --release build/release
    python scripts/v2/build_release.py publish --release build/release --env staging
    python scripts/v2/build_release.py rollback --env staging [--version VERSION_ID]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
MANIFEST = "release-manifest.json"
MAX_FILES = 20_000                       # Workers static assets, Free plan (Paid allows 100,000)
MAX_FILE_BYTES = 25 * 1024 * 1024        # 25 MiB per asset
TEXT_SUFFIXES = {".json", ".html", ".js", ".css", ".txt", ".xml", ".svg", ".webmanifest", ""}
SECRET_PATTERNS = [
    re.compile(r"sk-ant-[A-Za-z0-9_-]{16,}"),
    re.compile(r"AKIA[0-9A-Z]{16}"),
    re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----"),
    re.compile(r"(?i)(r2_secret_access_key|turnstile_secret|cloudflare_api_token)\s*[=:]\s*['\"]?[A-Za-z0-9/+_-]{16,}"),
]
DEEP_LINK = re.compile(r"^https://archive\.org/details/([^/]+)/page/n(\d+)$")
SITE_WORKER = REPO / "worker" / "site"


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def git_commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "HEAD"], cwd=REPO, capture_output=True, text=True,
                              check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def file_table(root: Path) -> dict:
    out = {}
    for path in sorted(p for p in root.rglob("*") if p.is_file() and p.name != MANIFEST):
        rel = path.relative_to(root).as_posix()
        out[rel] = {"sha256": sha256_file(path), "bytes": path.stat().st_size}
    return out


# --- assemble -------------------------------------------------------------------------------------

def empty_folder(folder: Path) -> None:
    """Remove everything inside folder (creating it when missing). The folder itself is kept: on a
    synced Windows folder, deleting the directory can be refused while its contents are not."""
    folder.mkdir(parents=True, exist_ok=True)
    for child in folder.iterdir():
        if child.is_dir():
            shutil.rmtree(child)
        else:
            child.unlink()

def assemble(release_id: str, web: Path, data: Path, static: Path, out: Path, api_origin: str) -> Path:
    if not (web / "index.html").exists():
        raise SystemExit(f"{web} has no index.html: build the web app first (npm run build:static)")
    if not (data / "export.json").exists():
        raise SystemExit(f"{data} has no export.json: run scripts/v2/export_site_data.py first")
    empty_folder(out)
    shutil.copytree(web, out, dirs_exist_ok=True)
    shutil.copytree(data, out / "data", dirs_exist_ok=True)
    if not re.fullmatch(r"https://[a-z0-9.-]+", api_origin):
        raise SystemExit(f"--api-origin must be an https origin with no path, got {api_origin!r}")
    headers = (static / "_headers.template").read_text(encoding="utf-8").replace("{api_origin}", api_origin)
    (out / "_headers").write_text(headers, encoding="utf-8")
    shutil.copyfile(static / "_redirects", out / "_redirects")
    export = json.loads((data / "export.json").read_text(encoding="utf-8"))
    manifest = {
        "release_id": release_id,
        "git_commit": git_commit(),
        "built_at": datetime.now(timezone.utc).replace(microsecond=0).isoformat(),
        "data_export": export,
        "api_origin": api_origin,
        "files": file_table(out),
    }
    (out / MANIFEST).write_text(json.dumps(manifest, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    print(f"assembled {out}: {len(manifest['files'])} files")
    return out


# --- gate -----------------------------------------------------------------------------------------

def gate(release: Path, allow_missing_path: Path) -> list[str]:
    """Every problem with the release as it will be published. Empty means it may ship."""
    sys.path.insert(0, str(REPO / "src"))
    from archive_debugger import editorial
    from archive_debugger import scopes as scope_registry
    from archive_debugger.api.cache import canonical_data_sha256
    from archive_debugger.generate.answer import generation_meta
    from archive_debugger.generate.cli import load_generate_config, sent_temperature

    problems: list[str] = []
    manifest_path = release / MANIFEST
    if not manifest_path.exists():
        return [f"no {MANIFEST}"]
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))

    # The manifest describes exactly the files present.
    actual = file_table(release)
    if set(actual) != set(manifest["files"]):
        extra = sorted(set(actual) - set(manifest["files"]))[:5]
        gone = sorted(set(manifest["files"]) - set(actual))[:5]
        problems.append(f"manifest does not list the files present (unlisted {extra}, missing {gone})")
    for rel, row in actual.items():
        listed = manifest["files"].get(rel)
        if listed and listed["sha256"] != row["sha256"]:
            problems.append(f"{rel}: sha256 differs from the manifest")

    # Workers static assets limits.
    if len(actual) + 1 > MAX_FILES:
        problems.append(f"{len(actual) + 1} files, over the {MAX_FILES} limit")
    for rel, row in actual.items():
        if row["bytes"] > MAX_FILE_BYTES:
            problems.append(f"{rel}: {row['bytes']} bytes, over the 25 MiB per-file limit")

    # No secret-looking text anywhere.
    for rel in actual:
        path = release / rel
        if path.suffix.lower() not in TEXT_SUFFIXES:
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for pattern in SECRET_PATTERNS:
            if pattern.search(text):
                problems.append(f"{rel}: text that looks like a secret ({pattern.pattern[:24]}...)")

    # The web source never renders raw HTML (archival text is untrusted).
    for path in (REPO / "web" / "src").rglob("*.tsx"):
        if "dangerouslySetInnerHTML" in path.read_text(encoding="utf-8"):
            problems.append(f"{path.relative_to(REPO).as_posix()}: renders raw HTML")

    data = release / "data"
    notes = json.loads((data / "editorial_notes.json").read_text(encoding="utf-8"))
    retired = {s["id"] for s in editorial.load_retired(REPO / editorial.DEFAULT_RETIRED)}
    allow = json.loads(allow_missing_path.read_text(encoding="utf-8")) if allow_missing_path.exists() else {}
    scopes_view = json.loads((data / "scopes.json").read_text(encoding="utf-8"))
    for scope_row in scopes_view["scopes"]:
        scope = scope_row["name"]
        base = data / scope
        resolved = scope_registry.resolve_scope(scope)
        gcfg = load_generate_config(Path(resolved.config_path))
        kind, model = gcfg["provider"], gcfg["model"]
        want = generation_meta(provider=kind, model=model, temperature=sent_temperature(kind, gcfg),
                               max_tokens=gcfg["max_tokens"], top_k=gcfg["top_k"])

        # Stories: comparability blocks, captions within them, no retired story featured.
        stories = json.loads((base / "stories.json").read_text(encoding="utf-8"))
        for s in stories:
            if not s.get("comparability") or s["comparability"].get("outcome") not in editorial.COMPARISON_OUTCOMES:
                problems.append(f"{scope} story {s.get('id')}: no valid comparability block")
            if s.get("id") in retired and set(s.get("surfaces") or []) & {"hero", "gallery", "attract"}:
                problems.append(f"{scope} story {s['id']}: retired but on a featured surface")
            for sentence_problem in editorial.overclaims(s.get("caption", ""), s["comparability"]["outcome"]) \
                    if s.get("comparability") else []:
                problems.append(f"{scope} story {s.get('id')}: caption overstates its comparability: {sentence_problem}")
        if sum(1 for s in stories if "hero" in (s.get("surfaces") or [])) > 1:
            problems.append(f"{scope}: more than one hero story")

        # Recorded answers.
        index = json.loads((base / "answers" / "index.json").read_text(encoding="utf-8"))
        if index.get("data_sha256") != canonical_data_sha256(scope):
            problems.append(f"{scope}: recorded answers were exported from data other than the published files")
        missing = sorted(e["label"] for e in index["answers"] if not e.get("file"))
        allowed = sorted((allow.get(scope) or {}).get("labels", []))
        if missing != allowed:
            problems.append(f"{scope}: curated questions without a recorded answer {missing}, "
                            f"allowed by config/release_allow_missing.json {allowed}")
        for entry in index["answers"]:
            if not entry.get("file"):
                continue
            label = entry["label"]
            response = json.loads((base / entry["file"]).read_text(encoding="utf-8"))
            answer = response.get("answer") or {}
            gen = answer.get("generation") or {}
            if not (answer.get("cached") or {}).get("created_at"):
                problems.append(f"{scope} {label}: recorded answer does not say when it was generated")
            for field in ("provider", "model", "prompt_sha256", "top_k", "temperature"):
                if gen.get(field) != want[field]:
                    problems.append(f"{scope} {label}: generation {field} {gen.get(field)!r} is not the configured {want[field]!r}")
            if response.get("degraded"):
                problems.append(f"{scope} {label}: a limited-mode response was recorded as an answer")
            evidence = {row["passage_id"]: row for row in response.get("evidence") or []}
            verified = {c["passage_id"] for c in answer.get("verified_citations") or []}
            for cite in answer.get("verified_citations") or []:
                row = evidence.get(cite["passage_id"])
                if row is None:
                    problems.append(f"{scope} {label}: citation {cite['passage_id']} is not in its evidence")
                    continue
                link = DEEP_LINK.match(row.get("deep_link") or "")
                if not link or link.group(1) != row["item_id"] or int(link.group(2)) != int(row["leaf_index"]):
                    problems.append(f"{scope} {label}: citation {cite['passage_id']} has no page link to its own page")
                if not (row.get("snippet") or "").strip():
                    problems.append(f"{scope} {label}: citation {cite['passage_id']} has no page text")
            for sentence in answer.get("sentences") or []:
                for pid in sentence.get("cited_ids") or []:
                    if pid not in verified:
                        problems.append(f"{scope} {label}: a sentence cites {pid}, which was not verified")
            for note in editorial.notes_for_answer(notes, scope, entry["question"], cached=True):
                if note["id"] not in {n["id"] for n in response.get("editorial_notes") or []}:
                    problems.append(f"{scope} {label}: dated note {note['id']} is not attached")
    return problems


# --- publish and rollback -------------------------------------------------------------------------

def wrangler(args: list[str]) -> subprocess.CompletedProcess:
    return subprocess.run(["npx", "wrangler", *args], cwd=SITE_WORKER, capture_output=True, text=True,
                          shell=sys.platform == "win32")


def publish(release: Path, env: str, allow_missing: Path) -> int:
    problems = gate(release, allow_missing)
    if problems:
        print("REFUSED: the release did not pass its gates:", file=sys.stderr)
        for p in problems:
            print(f"  - {p}", file=sys.stderr)
        return 1
    manifest = json.loads((release / MANIFEST).read_text(encoding="utf-8"))
    current = SITE_WORKER / "release"
    if current.exists():
        shutil.rmtree(current)
    shutil.copytree(release, current)
    upload = wrangler(["versions", "upload", "--env", env, "--tag", manifest["release_id"],
                       "--message", f"release {manifest['release_id']} ({manifest['git_commit'][:12]})"])
    print(upload.stdout)
    if upload.returncode != 0:
        print(upload.stderr, file=sys.stderr)
        return upload.returncode
    match = re.search(r"Worker Version ID:\s*([0-9a-f-]{36})", upload.stdout)
    if not match:
        print("uploaded, but no version id was found in the output; deploy it with wrangler versions deploy", file=sys.stderr)
        return 1
    deploy = wrangler(["versions", "deploy", f"{match.group(1)}@100%", "--env", env, "-y",
                       "--message", f"release {manifest['release_id']}"])
    print(deploy.stdout)
    if deploy.returncode != 0:
        print(deploy.stderr, file=sys.stderr)
    return deploy.returncode


def rollback(env: str, version: str | None) -> int:
    args = ["rollback", "--env", env, "--message", "rollback"]
    if version:
        args.insert(1, version)
    result = wrangler(args)
    print(result.stdout)
    if result.returncode != 0:
        print(result.stderr, file=sys.stderr)
    return result.returncode


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    a = sub.add_parser("assemble")
    a.add_argument("--release-id", required=True)
    a.add_argument("--web", type=Path, default=REPO / "web" / "dist")
    a.add_argument("--data", type=Path, default=REPO / "site" / "data")
    a.add_argument("--static", type=Path, default=REPO / "site" / "static")
    a.add_argument("--out", type=Path, default=REPO / "build" / "release")
    a.add_argument("--api-origin", required=True, help="the engine Worker, e.g. https://api.archiveargues.org")
    g = sub.add_parser("gate")
    g.add_argument("--release", type=Path, default=REPO / "build" / "release")
    g.add_argument("--allow-missing", type=Path, default=REPO / "config" / "release_allow_missing.json")
    p = sub.add_parser("publish")
    p.add_argument("--release", type=Path, default=REPO / "build" / "release")
    p.add_argument("--env", choices=["staging", "production"], required=True)
    p.add_argument("--allow-missing", type=Path, default=REPO / "config" / "release_allow_missing.json")
    r = sub.add_parser("rollback")
    r.add_argument("--env", choices=["staging", "production"], required=True)
    r.add_argument("--version", default=None, help="a Worker version id; default: the version before the current one")
    args = parser.parse_args(argv)

    if args.command == "assemble":
        assemble(args.release_id, args.web, args.data, args.static, args.out, args.api_origin)
        return 0
    if args.command == "gate":
        problems = gate(args.release, args.allow_missing)
        if problems:
            print(f"GATE FAILED: {len(problems)} problems", file=sys.stderr)
            for problem in problems:
                print(f"  - {problem}", file=sys.stderr)
            return 1
        print("gate passed")
        return 0
    if args.command == "publish":
        return publish(args.release, args.env, args.allow_missing)
    return rollback(args.env, args.version)


if __name__ == "__main__":
    sys.exit(main())
